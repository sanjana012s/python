# 1 \n – New line (MOST IMPORTANT)
print("Hello\nWorld")
# Hello
# World

# 2 \t – Tab space
print("Hello\tWorld")
# Hello   World

# 3 \\ – Backslash
print("Path: C:\\Users\\Admin")
# Path: C:\Users\Admin

# 4 \' – Single quote
print('It\'s Python')
# It's Python

# 5 \" – Double quote
print("He said \"Hello\"")
# He said "Hello"

# 6 \r – Carriage return (overwrites line)
print("Hello\rWorld")
# World

# 7 \b – Backspace
print("Helloo\b")
# Hello

# 8 Raw string r"" – ignores escape sequences
print(r"Hello\nWorld")
# Hello\nWorld

# 9 \a – Alert / bell sound
print("\a")
# Beep sound (system dependent)

# 10 \f – Form feed
print("Hello\fWorld")
# Hello World

# 11 \v – Vertical tab
print("Hello\vWorld")
# Hello
#       World

# 12 \0 – Null character
print("Hi\0Hello")
# Hi Hello

# 13 \101 – Octal value
print("\101")
# A

# 14 \x41 – Hexadecimal value
print("\x41")
# A

# 15 Multiple escape together
print("Name:\tSanjana\nCity:\tVaranasi")
# Formatted output

# 16 New line at end
print("Python\n")
# Python

# 17 Tab with numbers
print("1\t2\t3")
# 1   2   3

# 18 Quote inside quote
print("Python is \"Easy\"")
# Python is "Easy"

# 19 Windows path safe
print(r"C:\new\test")
# C:\new\test

# 20 Escape sequence in file/text formatting
print("Roll No:\t01\nResult:\tPass")
# Formatted text
